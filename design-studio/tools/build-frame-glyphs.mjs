// Builds src/frame-glyphs.js: outlines of A–Z, 0–9 and Thai consonants ก–ฮ in Kanit ExtraBold (SIL OFL 1.1)
// used as photo-frame shapes ("letter frames").
//   node tools/build-frame-glyphs.mjs [path/to/Kanit-ExtraBold.ttf]
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import opentype from 'opentype.js';

let file = process.argv[2];
if (!file) {
  const css = execFileSync('curl', ['-sf', 'https://fonts.googleapis.com/css2?family=Kanit:wght@800']).toString();
  const url = css.match(/https:[^)]+\.ttf/)[0];
  file = path.join(os.tmpdir(), 'kanit-800.ttf');
  execFileSync('curl', ['-sfL', '-o', file, url]);
}
const font = opentype.parse(fs.readFileSync(file).buffer.slice(0));
const SIZE = 200;
const out = {};
const latin = [...'ABCDEFGHIJKLMNOPQRSTUVWXYZ'], digits = [...'0123456789'];
const thai = [...'กขฃคฅฆงจฉชซฌญฎฏฐฑฒณดตถทธนบปผฝพฟภมยรลวศษสหฬอฮ'];
for (const ch of [...latin, ...digits, ...thai]) {
  const p = font.getPath(ch, 0, 0, SIZE);
  const d = p.toPathData(1);
  if (!d) throw new Error('no glyph for ' + ch);
  out[ch] = d;
}
const dest = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'frame-glyphs.js');
fs.writeFileSync(dest, `// Generated by tools/build-frame-glyphs.mjs – glyph outlines of Kanit ExtraBold (© Cadson Demak, SIL Open Font License 1.1).\nexport const GLYPHS = ${JSON.stringify({ latin, digits, thai, d: out })};\n`);
console.log(Object.keys(out).length, 'glyphs,', (fs.statSync(dest).size / 1024).toFixed(0), 'KB');
